// Single source of truth: rubric/rubric.json and data/prompts.json.
// Generates rubric/RUBRIC.md and grader/rubric.js, and checks the prompt hash.
// Run: node scripts/build.mjs
// Licence: MIT.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const errors = [];

const rubric = JSON.parse(read('rubric/rubric.json'));
const prompts = JSON.parse(read('data/prompts.json'));

// Validation: every row needs the three anchors and an id the grader can key on.
const rows = [rubric.holistic, ...rubric.dimensions];
const ids = new Set();
for (const r of rows) {
  if (ids.has(r.id)) errors.push(`duplicate id ${r.id}`);
  ids.add(r.id);
  for (const k of ['1', '3', '5']) {
    if (!r.anchors?.[k]) errors.push(`${r.id}: missing anchor ${k}`);
  }
  if (!r.question) errors.push(`${r.id}: missing question`);
}
for (const p of prompts.prompts) {
  if (!p.id || !p.text) errors.push(`prompt missing id or text: ${JSON.stringify(p)}`);
}

// Rubric markdown
const md = [];
md.push(`# ${rubric.title}`, '');
md.push(`Version ${rubric.rubric_version}. ${rubric.status}`, '');
md.push('Generated from `rubric/rubric.json` by `scripts/build.mjs`. Do not edit this file by hand.', '');
md.push('## Scope', '', rubric.scope, '', '### Not graded', '');
for (const n of rubric.not_graded) md.push(`- ${n}`);
md.push('', '## Rules for the grader', '');
rubric.rules.forEach((r, i) => md.push(`${i + 1}. ${r}`));
md.push('', '## Scale', '', 'Whole numbers 1 to 5. Anchors are written for 1, 3 and 5. A 2 or a 4 means between the neighbouring anchors.', '');
md.push(`## ${rubric.holistic.id}. ${rubric.holistic.name} (graded first)`, '', `**${rubric.holistic.question}**`, '');
for (const k of ['1', '3', '5']) md.push(`- **${k}.** ${rubric.holistic.anchors[k]}`);
md.push('', `*${rubric.holistic.note}*`, '');
for (const d of rubric.dimensions) {
  md.push(`## ${d.id}. ${d.name}`, '', `**${d.question}**`, '');
  for (const k of ['1', '3', '5']) md.push(`- **${k}.** ${d.anchors[k]}`);
  md.push('', `Look for: ${d.look_for.join('; ')}.`, '');
  md.push(`Good example: ${d.examples.good}`, '', `Bad example: ${d.examples.bad}`, '');
}
md.push('## Measured facts', '', rubric.measured_facts_note, '');
md.push('## Crosswalk', '', rubric.crosswalk.note, '');
for (const r of rows) md.push(`- **${r.id} ${r.name}:** ${rubric.crosswalk[r.id]}`);
md.push('');
writeFileSync(join(root, 'rubric/RUBRIC.md'), md.join('\n'));

// Grader data: rubric only, no prompts hash logic in the page.
const graderRubric = {
  rubric_version: rubric.rubric_version,
  rules: rubric.rules,
  holistic: rubric.holistic,
  dimensions: rubric.dimensions.map(({ id, name, question, anchors, look_for }) => ({ id, name, question, anchors, look_for })),
};
writeFileSync(join(root, 'grader/rubric.js'), `// Generated by scripts/build.mjs from rubric/rubric.json. Do not edit.\nwindow.RUBRIC = ${JSON.stringify(graderRubric, null, 2)};\n`);

// Pre-registration check. A DRAFT set may differ from its hash; a FROZEN set may not.
const hashFile = join(root, 'data/prompts.sha256');
const actual = createHash('sha256').update(readFileSync(join(root, 'data/prompts.json'))).digest('hex');
if (existsSync(hashFile)) {
  const recorded = readFileSync(hashFile, 'utf8').trim().split(/\s+/)[0];
  if (recorded !== actual) {
    const msg = `prompts.json hash ${actual} does not match data/prompts.sha256 (${recorded})`;
    if (prompts.status === 'FROZEN') errors.push(msg); else console.warn(`warning (status ${prompts.status}): ${msg}`);
  } else {
    console.log(`prompts hash matches: ${actual}`);
  }
} else {
  console.warn('no data/prompts.sha256 yet');
}

if (errors.length) {
  console.error('Validation errors:\n- ' + errors.join('\n- '));
  process.exit(1);
}
console.log(`ok: ${rows.length} graded rows, ${prompts.prompts.length} prompts, wrote rubric/RUBRIC.md and grader/rubric.js`);
